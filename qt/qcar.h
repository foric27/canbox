#ifndef QCAR_H
#define QCAR_H

/**
 * @brief Перечисление виртуальных элементов автомобиля для эмулятора
 *
 * Определяет индексы для доступа к массиву qcar_state[].
 * Каждый элемент соответствует кнопке в UI главного окна.
 */
enum e_qcar_t
{
	e_fl_door = 0,  /**< Передняя левая дверь */
	e_fr_door,      /**< Передняя правая дверь */
	e_rl_door,      /**< Задняя левая дверь */
	e_rr_door,      /**< Задняя правая дверь */
	e_bonnet,       /**< Капот */
	e_tailgate,     /**< Багажник */

	e_belt,         /**< Ремень безопасности водителя */

	e_qcar_nums     /**< Количество элементов (конец перечисления) */
};

/**
 * @brief Глобальный массив состояний виртуального автомобиля
 *
 * Индексируется значениями e_qcar_t. 0 — выключено, 1 — включено.
 * Заполняется из GUI (кнопки главного окна), читается в qcar_process().
 */
extern uint8_t qcar_state[e_qcar_nums];

#endif
