#ifndef LOG_LEVELS_H
#define LOG_LEVELS_H

/**
 * @brief Уровни журналирования для отладочного виджета
 *
 * Используются в wdg_dbg_t для фильтрации сообщений
 * и выбора цвета отображения.
 */
enum e_log_level
{
	e_log_warn = 0,   /**< Предупреждения (красный цвет) */
	e_log_status = 1, /**< Статусные сообщения */
	e_log_info = 2,   /**< Информационные сообщения */
	e_log_debug = 3,  /**< Отладочные сообщения (синий цвет) */
	e_log_all         /**< Показывать все сообщения */
};

#endif
